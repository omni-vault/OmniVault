// Turns vendor/eff_large_wordlist.txt (EFF Large Wordlist for passphrases, CC BY 3.0 US) into src/lib/eff-wordlist.js:
// the 7776 words in their original order, without the dice numbers. The file must match the published original
// (SHA-256 below); run after replacing it:  node tools/wordlist-build.mjs
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

export const EFF_SHA256 = 'addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e';
const src = await readFile('vendor/eff_large_wordlist.txt', 'utf8');
const sha = createHash('sha256').update(src).digest('hex');
if (sha !== EFF_SHA256) throw new Error(`vendor/eff_large_wordlist.txt has SHA-256 ${sha}, expected ${EFF_SHA256}`);
const words = src.trimEnd().split('\n').map((line, i) => {
  const [dice, word] = line.split('\t');
  if (!/^[1-6]{5}$/.test(dice) || !/^[a-z-]+$/.test(word)) throw new Error(`Line ${i + 1} unexpected: ${line}`);
  return word;
});
if (words.length !== 7776 || new Set(words).size !== 7776) throw new Error('Expected 7776 distinct words');
await writeFile('src/lib/eff-wordlist.js', `// Generated by tools/wordlist-build.mjs from vendor/eff_large_wordlist.txt – do not edit.
// EFF Large Wordlist for passphrases (https://www.eff.org/dice), Electronic Frontier Foundation, CC BY 3.0 US.
// Source SHA-256: ${sha}
export const EFF_WORDS = ${JSON.stringify(words.join(' '))};
`);
console.log(`${words.length} words → src/lib/eff-wordlist.js`);

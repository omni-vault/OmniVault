// Turns vendor/public_suffix_list.dat (Public Suffix List, MPL-2.0) into src/lib/psl-data.js: the rules in
// ASCII form (punycode, as URL.hostname returns them), comments dropped. Run after updating the list:
//   node tools/psl-build.mjs
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { domainToASCII } from 'node:url';

const src = await readFile('vendor/public_suffix_list.dat', 'utf8');
const rules = [];
for (const raw of src.split('\n')) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith('//')) continue;
  const prefix = line.match(/^(!|\*\.)?/)[0];
  const ascii = domainToASCII(line.slice(prefix.length));
  if (!ascii) throw new Error(`Rule cannot be converted: ${line}`);
  rules.push(prefix + ascii);
}
const sha = createHash('sha256').update(src).digest('hex');
await writeFile('src/lib/psl-data.js', `// Generated by tools/psl-build.mjs from vendor/public_suffix_list.dat – do not edit.
// Public Suffix List (https://publicsuffix.org), Mozilla Public License 2.0. Source SHA-256: ${sha}
export const PSL_RULES = ${JSON.stringify(rules.join(' '))};
`);
console.log(`${rules.length} Regeln → src/lib/psl-data.js`);
